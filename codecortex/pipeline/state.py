"""Saved per-project index: build once, then answer queries from disk.

``codecortex index`` writes the graph and its expensive derived results
(centrality, cluster memberships) to ``<project>/.codecortex/``. Later
``query``/``explain`` runs load that state, re-parse only the files whose
size or mtime changed, and skip the rest of the build. On a 600-file
repository that is the difference between a ~80 s rebuild per question and a
sub-second answer.

Layout:
    .codecortex/
      .gitignore   "*" — the directory never shows up in ``git status``
      graph.db     SQLite copy of the in-memory GraphStore (lossless)
      state.json   build settings, file fingerprints, centrality, clusters
      embeddings.npy / embeddings.json
                   node vectors and the file fingerprints they were made from

After an incremental refresh the stored centrality and clusters still
describe the previous graph; they are kept (and marked ``derived_stale``)
because recomputing them dominates build time. ``codecortex index`` rebuilds
everything.
"""

from __future__ import annotations

import dataclasses
import json
import logging
import os
import sqlite3
import time
from pathlib import Path
from typing import Callable, Optional

from codecortex.version import __version__

logger = logging.getLogger(__name__)

STATE_DIR_NAME = ".codecortex"
STATE_FORMAT = 1

# Past this many changed files *and* this share of the project, a full
# rebuild is cheaper than removing and re-adding each file's nodes.
_REBUILD_MIN_FILES = 50
_REBUILD_FRACTION = 0.3

ProgressCallback = Callable[[int, int, Path], None]


def state_dir_for(root: Path) -> Path:
    return Path(root).resolve() / STATE_DIR_NAME


def has_saved_index(root: Path) -> bool:
    return (state_dir_for(root) / "state.json").is_file()


@dataclasses.dataclass
class OpenResult:
    """How ``open_pipeline`` produced its pipeline, for CLI reporting."""

    source: str  # "built" | "loaded"
    reparsed: int = 0
    removed: int = 0
    saved: bool = False


def _fingerprint(path: Path) -> list[int]:
    stat = path.stat()
    return [stat.st_mtime_ns, stat.st_size]


def _walk(root: Path, pipeline) -> dict[str, list[int]]:
    """Fingerprint every file the pipeline's settings select under root."""
    from codecortex.core.file_walker import walk_source_files

    cfg = pipeline.config
    ext_map = pipeline._build_ext_parser_map(pipeline._languages)
    files = walk_source_files(
        root,
        extensions=ext_map.keys(),
        exclude_dirs=cfg.exclude_dirs,
        exclude_paths=pipeline._exclude_paths,
        respect_gitignore=cfg.respect_gitignore,
    )
    found = {}
    for path in files:
        try:
            found[str(path)] = _fingerprint(path)
        except OSError:
            continue
    return found


def _atomic_write(path: Path, text: str) -> None:
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def _remove_file(store, file_path: str) -> None:
    """Drop what a file declares: its nodes and the edges written in it.

    Unlike ``CPGBuilder.remove_file`` this keeps edges from other files that
    point into this one. Edges join nodes by name, so once the file is
    re-parsed those callers attach to its new nodes again; deleting them
    would lose every inbound call from a file that did not change.
    """
    with store._tx() as cur:
        cur.execute("DELETE FROM edges WHERE file_path = ?", (file_path,))
        cur.execute("DELETE FROM nodes WHERE file_path = ?", (file_path,))


def save_state(pipeline, root: Path, derived_stale: bool = False) -> Path:
    """Write the pipeline's graph and derived results under root/.codecortex."""
    root = Path(root).resolve()
    state_dir = state_dir_for(root)
    state_dir.mkdir(parents=True, exist_ok=True)
    ignore = state_dir / ".gitignore"
    if not ignore.exists():
        ignore.write_text("# Generated by codecortex; safe to delete.\n*\n", encoding="utf-8")

    db_tmp = state_dir / "graph.db.tmp"
    db_tmp.unlink(missing_ok=True)
    target = sqlite3.connect(db_tmp)
    try:
        pipeline.graph_store._conn.backup(target)
    finally:
        target.close()
    os.replace(db_tmp, state_dir / "graph.db")

    files = {}
    for path in pipeline._indexed_files:
        try:
            files[str(path)] = _fingerprint(path)
        except OSError:
            continue

    state = {
        "format": STATE_FORMAT,
        "codecortex_version": __version__,
        "root": str(root),
        "saved_at": time.time(),
        "languages": pipeline._languages,
        "exclude_paths": pipeline._exclude_paths,
        "config": dataclasses.asdict(pipeline.config),
        "files": files,
        "centrality": {
            name: dataclasses.asdict(score)
            for name, score in (pipeline._centrality_scores or {}).items()
        },
        "clusters": pipeline._cluster_memberships or {},
        "derived_stale": derived_stale,
    }
    _atomic_write(state_dir / "state.json", json.dumps(state, separators=(",", ":")))
    if pipeline.embedding_store is not None:
        _save_embeddings(pipeline, state_dir, files)
    logger.info("Saved index to %s", state_dir)
    return state_dir


def _save_embeddings(pipeline, state_dir: Path, files: dict) -> None:
    """Write the node vectors, so a later run need not re-embed every node.

    For the model backends re-embedding means running the model over the
    whole project, so this is what keeps a query from taking minutes.
    """
    import numpy as np

    names, texts, matrix = pipeline.embedding_store.export_arrays()
    node_files = dict(
        pipeline.graph_store._conn.execute("SELECT qualified_name, file_path FROM nodes")
    )
    tmp = state_dir / "embeddings.npy.tmp"
    with open(tmp, "wb") as f:
        # float16 halves the file; cosine ranking does not notice the precision.
        np.save(f, matrix.astype("float16"))
    os.replace(tmp, state_dir / "embeddings.npy")
    meta = {
        "backend": pipeline.config.embedding_backend,
        "names": names,
        "texts": texts,
        "node_files": [node_files.get(name, "") for name in names],
        # Tracked apart from the graph's: a graph-only refresh (explain)
        # updates the graph but leaves these vectors behind.
        "files": files,
    }
    _atomic_write(state_dir / "embeddings.json", json.dumps(meta, separators=(",", ":")))


def _load_embeddings(root: Path, pipeline, current: dict[str, list[int]]):
    """(EmbeddingPipeline, refreshed) from saved vectors, or None to re-embed.

    Vectors of files changed since they were saved are dropped and those
    files re-embedded; everything else is reused as is.
    """
    import numpy as np

    state_dir = state_dir_for(root)
    try:
        meta = json.loads((state_dir / "embeddings.json").read_text(encoding="utf-8"))
        matrix = np.load(state_dir / "embeddings.npy").astype("float32")
    except (OSError, ValueError):
        return None
    embedding_pipeline = pipeline._new_embedding_pipeline()
    store = embedding_pipeline.embedding_store
    names = meta.get("names", [])
    if meta.get("backend") != pipeline.config.embedding_backend or matrix.shape != (
        len(names),
        store.provider.dimensions,
    ):
        return None

    store.load_arrays(names, meta["texts"], matrix)
    saved_files = meta.get("files", {})
    stale = {p for p, fp in current.items() if saved_files.get(p) != fp}
    stale.update(p for p in saved_files if p not in current)
    if stale:
        for name, file_path in zip(names, meta["node_files"]):
            if file_path in stale:
                store.remove(name)
        for file_path in stale:
            if file_path in current:
                embedding_pipeline.index_file(file_path)
    return embedding_pipeline, bool(stale)


def _read_state(root: Path) -> Optional[dict]:
    path = state_dir_for(root) / "state.json"
    try:
        state = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    if (
        state.get("format") != STATE_FORMAT
        # The graph schema can change between releases; rebuild once after
        # an upgrade rather than read a graph this version might misread.
        or state.get("codecortex_version") != __version__
        or state.get("root") != str(Path(root).resolve())
        or not (state_dir_for(root) / "graph.db").is_file()
    ):
        return None
    return state


def load_state(
    root: Path,
    config_overrides: Optional[dict] = None,
    on_progress: Optional[ProgressCallback] = None,
    derived: bool = True,
):
    """Load a saved index and bring it up to date with the working tree.

    With ``derived=False`` only the graph is loaded — enough for lookups such
    as ``explain`` — and embeddings, adjacency and the retrieval layer are
    not built.

    Returns ``(pipeline, OpenResult)``, or None when there is no usable saved
    index (none written, older format or release, different root, or so much
    changed that a rebuild is cheaper).
    """
    from codecortex.graph.cpg_builder import CPGBuilder
    from codecortex.graph.graph_store import GraphStore
    from codecortex.pipeline.context_builder import (
        CodeCortexPipeline,
        PipelineConfig,
        PipelineStats,
    )
    from codecortex.ranking.centrality_engine import NodeScore

    root = Path(root).resolve()
    state = _read_state(root)
    if state is None:
        return None

    try:
        saved_config = dict(state["config"])
        saved_config.update(config_overrides or {})
        config = PipelineConfig(**saved_config)
        centrality = {name: NodeScore(**score) for name, score in state["centrality"].items()}
    except (KeyError, TypeError) as e:
        logger.info("Saved index unreadable (%s); rebuilding", e)
        return None

    pipeline = CodeCortexPipeline(config)
    pipeline._languages = state.get("languages")
    pipeline._exclude_paths = state.get("exclude_paths") or []

    store = GraphStore(":memory:")
    source = sqlite3.connect(state_dir_for(root) / "graph.db")
    try:
        source.backup(store._conn)
    finally:
        source.close()
    pipeline._store = store

    saved_files: dict[str, list[int]] = state["files"]
    current = _walk(root, pipeline)
    changed = [p for p, fp in current.items() if saved_files.get(p) != fp]
    removed = [p for p in saved_files if p not in current]
    churn = len(changed) + len(removed)
    if churn > _REBUILD_MIN_FILES and churn > _REBUILD_FRACTION * len(current):
        return None

    if changed or removed:
        builder = CPGBuilder(
            store,
            enable_cfg=config.enable_cfg and not config.on_demand_cfg,
            enable_dfg=config.enable_dfg and not config.on_demand_dfg,
            enable_endpoints=config.enable_endpoints,
        )
        for path in removed + [p for p in changed if p in saved_files]:
            _remove_file(store, path)
        ext_map = pipeline._build_ext_parser_map(pipeline._languages)
        for index, path in enumerate(changed, start=1):
            file_path = Path(path)
            parser = ext_map.get(file_path.suffix.lstrip(".").lower())
            if parser is not None:
                try:
                    source_text = file_path.read_text(encoding="utf-8", errors="replace")
                    builder.ingest(parser.parse(source_text, path))
                except Exception as e:
                    logger.debug("Error parsing %s: %s", path, e)
            if on_progress is not None:
                on_progress(index, len(changed), file_path)

    pipeline._indexed_files = [Path(p) for p in current]
    embeddings_refreshed = False
    if derived:
        loaded = _load_embeddings(root, pipeline, current)
        if loaded is None:
            embedding_pipeline, embeddings_refreshed = None, True  # embedded below; save them
        else:
            embedding_pipeline, embeddings_refreshed = loaded
        pipeline._build_derived(
            PipelineStats(),
            centrality=centrality,
            cluster_memberships=state["clusters"],
            embedding_pipeline=embedding_pipeline,
        )
    else:
        # Carried through so a save below keeps them.
        pipeline._centrality_scores = centrality
        pipeline._cluster_memberships = state["clusters"]

    result = OpenResult(source="loaded", reparsed=len(changed), removed=len(removed))
    if changed or removed or embeddings_refreshed:
        stale = bool(state.get("derived_stale")) or bool(changed or removed)
        save_state(pipeline, root, derived_stale=stale)
        result.saved = True
    return pipeline, result


def open_pipeline(
    root: Path,
    config=None,
    languages: Optional[list[str]] = None,
    on_progress: Optional[ProgressCallback] = None,
    *,
    rebuild: bool = False,
    save: bool = True,
    config_overrides: Optional[dict] = None,
    derived: bool = True,
):
    """A ready pipeline for root: from the saved index when possible.

    A saved index is used only when ``languages`` is unset or matches the
    one it was built with; otherwise the request is for a different graph.
    ``config_overrides`` (retrieval settings) apply to a loaded index; the
    build settings it was saved with are kept. ``derived=False`` skips the
    retrieval layers when loading (a fresh build always runs every phase).
    """
    from codecortex.pipeline.context_builder import CodeCortexPipeline

    root = Path(root).resolve()
    if not rebuild:
        state = _read_state(root)
        wanted = sorted(languages) if languages else None
        saved = sorted(state["languages"]) if state and state.get("languages") else None
        if state is not None and (wanted is None or wanted == saved):
            loaded = load_state(root, config_overrides, on_progress, derived=derived)
            if loaded is not None:
                return loaded

    pipeline = CodeCortexPipeline(config)
    pipeline.build(root, languages=languages, on_progress=on_progress)
    result = OpenResult(source="built")
    if save:
        save_state(pipeline, root)
        result.saved = True
    return pipeline, result
